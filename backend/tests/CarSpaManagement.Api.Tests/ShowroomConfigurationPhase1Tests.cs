        await db.ShowroomVehicleWorks.AddAsync(existingWork);
        await db.SaveChangesAsync();

        // Updating notes while keeping the inactive vehicle type unchanged should NOT crash or throw
        var updateReq = new UpdateShowroomVehicleWorkRequest
        {
            VehicleTypeId = vtInactive.Id, // Unchanged
            Notes = "Updated notes"
        };

        var updated = await opsService.UpdateVehicleWorkAsync(showroom.Id, existingWork.Id, updateReq);
        Assert.NotNull(updated);
        Assert.Equal("Updated notes", updated!.Notes);
        Assert.Equal(vtInactive.Id, updated.VehicleTypeId);
    }

