        var showroom = new Showroom { Id = Guid.NewGuid(), MasterId = "SR1", Name = "Main", Address = "A", Phone = "9876543210", IsActive = true, CreatedAt = DateTime.UtcNow };
        var staff = new Staff { Id = Guid.NewGuid(), StaffMasterId = "ST1", Name = "Ravi", PhoneNumber = "9876543211", IsActive = true, CreatedAt = DateTime.UtcNow };
        var vtInactive = new ShowroomVehicleType { Id = Guid.NewGuid(), Code = "OLD_TYPE", Name = "Old Type", IsActive = false, CreatedAt = DateTime.UtcNow };
        var wtActive = new ShowroomWorkType { Id = Guid.NewGuid(), Code = "WASH", Name = "Wash", IsActive = true, CreatedAt = DateTime.UtcNow };
        var date = DateTime.UtcNow.Date;

        var existingWork = new ShowroomVehicleWork
        {
            Id = Guid.NewGuid(),
            ShowroomId = showroom.Id,
            StaffId = staff.Id,
            VehicleTypeId = vtInactive.Id,
            VehicleQuantity = 1,
            Date = date,
            Notes = "Old record notes",
            CreatedAt = DateTime.UtcNow
        };

        await db.Showrooms.AddAsync(showroom);
        await db.Staff.AddAsync(staff);
        await db.ShowroomVehicleTypes.AddAsync(vtInactive);
        await db.ShowroomWorkTypes.AddAsync(wtActive);
